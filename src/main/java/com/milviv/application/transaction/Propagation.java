package com.milviv.application.transaction;

/**
 * Поведение TransactionManager при наличии или отсутствии активной транзакции.
 */
public enum Propagation {
  
  /**
   * Присоединиться к существующей транзакции.
   * Если нет — создать новую.
   * Стандартный вариант для всех бизнес-операций.
   */
  REQUIRED,

  /**
   * Всегда создавать новую транзакцию.
   * Текущая транзакция приостанавливается на время выполнения.
   *
   * Используется для: audit log, outbox events.
   * Важно: новая транзакция видит только закоммиченные данные внешней транзакции.
   */
  REQUIRES_NEW,

  /**
   * Обязательно должна быть активная транзакция.
   * Если нет — бросает IllegalStateException.
   *
   * Используется для: внутренних методов, которые не должны
   * вызываться вне явного транзакционного контекста.
   */
  MANDATORY,

  /**
   * Присоединиться к существующей транзакции.
   * Если нет — открыть read-only транзакцию: запись в ней запрещена.
   * Используется для: read-only операций, запросов статистики.
   */
  SUPPORTS
}
