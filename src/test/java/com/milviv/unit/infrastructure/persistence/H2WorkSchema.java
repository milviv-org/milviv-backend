package com.milviv.unit.infrastructure.persistence;

import java.sql.SQLException;
import java.sql.Statement;

/**
 * Таблицы пользователей (только нужные колонки), целей, проектов, задач, планов, наград и баллов для H2.
 * Повторяют V1, V2, V3, V4, V7, V9, V10, V11, V12 (со стандартными вопросами), V13, V14 (ai_consents)
 * без возможностей PostgreSQL; внешние ключи с ON DELETE SET NULL сохранены.
 */
final class H2WorkSchema {

    private H2WorkSchema() {}

    static void create(Statement st) throws SQLException {
        st.execute("""
            CREATE TABLE users (
                id UUID PRIMARY KEY, email VARCHAR(255), password_hash VARCHAR(255), name VARCHAR(100),
                hidden_rewards_password_hash VARCHAR(255),
                created_at TIMESTAMP, updated_at TIMESTAMP, version BIGINT NOT NULL DEFAULT 0)""");
        st.execute("""
            CREATE TABLE goals (
                id UUID PRIMARY KEY, user_id UUID NOT NULL, title VARCHAR(255) NOT NULL, description TEXT,
                version BIGINT NOT NULL DEFAULT 0, created_at TIMESTAMP, updated_at TIMESTAMP)""");
        st.execute("""
            CREATE TABLE projects (
                id UUID PRIMARY KEY, user_id UUID NOT NULL, goal_id UUID REFERENCES goals(id) ON DELETE SET NULL,
                title VARCHAR(255) NOT NULL, description TEXT, calculated_difficulty VARCHAR(20),
                status VARCHAR(20) NOT NULL, deadline DATE, completed_at TIMESTAMP,
                created_at TIMESTAMP, updated_at TIMESTAMP, version BIGINT NOT NULL DEFAULT 0)""");
        st.execute("""
            CREATE TABLE tasks (
                id UUID PRIMARY KEY, user_id UUID NOT NULL, title VARCHAR(255) NOT NULL, description TEXT,
                difficulty VARCHAR(20) NOT NULL, points INTEGER NOT NULL CHECK (points BETWEEN 1 AND 1000),
                status VARCHAR(20) NOT NULL, start_date DATE, deadline DATE, reminder_at TIMESTAMP,
                completed_at TIMESTAMP,
                project_id UUID REFERENCES projects(id) ON DELETE SET NULL,
                goal_id UUID REFERENCES goals(id) ON DELETE SET NULL,
                created_at TIMESTAMP, updated_at TIMESTAMP, version BIGINT NOT NULL DEFAULT 0)""");
        st.execute("""
            CREATE TABLE task_completions (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id UUID NOT NULL,
                task_id UUID REFERENCES tasks(id) ON DELETE SET NULL,
                difficulty VARCHAR(20) NOT NULL, points INTEGER NOT NULL, planned_date DATE, deadline DATE,
                completed_at TIMESTAMP NOT NULL)""");
        st.execute("""
            CREATE TABLE plans (
                id UUID PRIMARY KEY, user_id UUID NOT NULL, task_id UUID REFERENCES tasks(id) ON DELETE CASCADE,
                title VARCHAR(255) NOT NULL, description TEXT, plan_date DATE, days_of_week SMALLINT ARRAY,
                time_from TIME NOT NULL, time_to TIME NOT NULL, created_at TIMESTAMP, updated_at TIMESTAMP)""");
        st.execute("""
            CREATE TABLE task_reschedules (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id UUID NOT NULL,
                task_id UUID REFERENCES tasks(id) ON DELETE SET NULL,
                from_date DATE NOT NULL, to_date DATE NOT NULL, rescheduled_at TIMESTAMP)""");
        st.execute("""
            CREATE TABLE rewards (
                id UUID PRIMARY KEY, user_id UUID NOT NULL, title VARCHAR(255) NOT NULL, description TEXT,
                cost INTEGER NOT NULL CHECK (cost > 0), hidden BOOLEAN NOT NULL DEFAULT FALSE,
                version BIGINT NOT NULL DEFAULT 0, created_at TIMESTAMP, updated_at TIMESTAMP)""");
        st.execute("""
            CREATE TABLE points_history (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id UUID NOT NULL, kind VARCHAR(20) NOT NULL,
                amount INTEGER NOT NULL, reason VARCHAR(255) NOT NULL,
                task_id UUID REFERENCES tasks(id) ON DELETE SET NULL,
                reward_id UUID REFERENCES rewards(id) ON DELETE SET NULL, created_at TIMESTAMP)""");
        st.execute("""
            CREATE TABLE ai_consents (
                user_id UUID PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE, accepted_at TIMESTAMP NOT NULL)""");
        st.execute("""
            CREATE TABLE user_sound_settings (
                user_id UUID NOT NULL, event VARCHAR(50) NOT NULL, sound VARCHAR(100) NOT NULL,
                PRIMARY KEY (user_id, event))""");
        st.execute("""
            CREATE TABLE reflection_questions (
                id UUID PRIMARY KEY, user_id UUID, text VARCHAR(500) NOT NULL, created_at TIMESTAMP)""");
        st.execute("""
            CREATE TABLE task_reflection_questions (
                task_id UUID NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
                question_id UUID NOT NULL REFERENCES reflection_questions(id) ON DELETE CASCADE,
                PRIMARY KEY (task_id, question_id))""");
        st.execute("""
            CREATE TABLE reflection_answers (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id UUID NOT NULL,
                completion_id BIGINT NOT NULL REFERENCES task_completions(id) ON DELETE CASCADE,
                question_id UUID REFERENCES reflection_questions(id) ON DELETE SET NULL,
                question_text VARCHAR(500) NOT NULL, answer TEXT NOT NULL, created_at TIMESTAMP)""");
        st.execute("""
            INSERT INTO reflection_questions (id, user_id, text, created_at) VALUES
                ('00000000-0000-0000-0000-000000000001', NULL, 'Что помогло выполнить задачу?', TIMESTAMP '2026-01-01 00:00:00'),
                ('00000000-0000-0000-0000-000000000002', NULL, 'Что помешало?', TIMESTAMP '2026-01-01 00:00:00'),
                ('00000000-0000-0000-0000-000000000003', NULL, 'Что можно было сделать иначе?', TIMESTAMP '2026-01-01 00:00:00')""");
    }
}
