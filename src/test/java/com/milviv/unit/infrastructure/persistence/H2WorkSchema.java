package com.milviv.unit.infrastructure.persistence;

import java.sql.SQLException;
import java.sql.Statement;

/**
 * Таблицы целей, проектов, задач и баллов для H2. Повторяют V2, V3, V7, V9, V11
 * без возможностей PostgreSQL; внешние ключи с ON DELETE SET NULL сохранены.
 */
final class H2WorkSchema {

    private H2WorkSchema() {}

    static void create(Statement st) throws SQLException {
        st.execute("""
            CREATE TABLE goals (
                id UUID PRIMARY KEY, user_id UUID NOT NULL, title VARCHAR(255) NOT NULL, description TEXT,
                version BIGINT NOT NULL DEFAULT 0, created_at TIMESTAMP, updated_at TIMESTAMP)""");
        st.execute("""
            CREATE TABLE projects (
                id UUID PRIMARY KEY, user_id UUID NOT NULL, goal_id UUID REFERENCES goals(id) ON DELETE SET NULL,
                title VARCHAR(255) NOT NULL, description TEXT, calculated_difficulty VARCHAR(20),
                status VARCHAR(20) NOT NULL, deadline DATE, completed_at TIMESTAMP,
                created_at TIMESTAMP, updated_at TIMESTAMP, version BIGINT NOT NULL DEFAULT 0)""");
        st.execute("""
            CREATE TABLE tasks (
                id UUID PRIMARY KEY, user_id UUID NOT NULL, title VARCHAR(255) NOT NULL, description TEXT,
                difficulty VARCHAR(20) NOT NULL, points INTEGER NOT NULL CHECK (points BETWEEN 1 AND 1000),
                status VARCHAR(20) NOT NULL, start_date DATE, deadline DATE, reminder_at TIMESTAMP,
                completed_at TIMESTAMP,
                project_id UUID REFERENCES projects(id) ON DELETE SET NULL,
                goal_id UUID REFERENCES goals(id) ON DELETE SET NULL,
                created_at TIMESTAMP, updated_at TIMESTAMP, version BIGINT NOT NULL DEFAULT 0)""");
        st.execute("""
            CREATE TABLE task_completions (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id UUID NOT NULL,
                task_id UUID REFERENCES tasks(id) ON DELETE SET NULL,
                difficulty VARCHAR(20) NOT NULL, points INTEGER NOT NULL, planned_date DATE, deadline DATE,
                completed_at TIMESTAMP NOT NULL)""");
        st.execute("""
            CREATE TABLE points_history (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id UUID NOT NULL, kind VARCHAR(20) NOT NULL,
                amount INTEGER NOT NULL, reason VARCHAR(255) NOT NULL,
                task_id UUID REFERENCES tasks(id) ON DELETE SET NULL, reward_id UUID, created_at TIMESTAMP)""");
    }
}
